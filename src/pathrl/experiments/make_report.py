"""Stage 12: generate docs/RESULTS.md from the summary CSVs (run `python main.py figures` first).

All numbers are read from outputs/results/summary/*.csv and formatted by code, never typed by
hand. Experiments without data are listed as pending.
"""

from __future__ import annotations

import json
import math

import numpy as np
import pandas as pd

from pathrl.utils.config import PROJECT_ROOT


def _fmt(v, digits=3):
    if v is None or (isinstance(v, float) and (math.isnan(v))):
        return "n/a"
    if isinstance(v, float) and math.isinf(v):
        return "never"
    if isinstance(v, (int, np.integer)):
        return str(v)
    if abs(v) >= 1000:
        return f"{v:,.0f}"
    return f"{v:.{digits}g}"


def _ci(row, m, digits=3):
    mean, lo, hi = row.get(f"{m}_mean"), row.get(f"{m}_ci_low"), row.get(f"{m}_ci_high")
    if lo is None or (isinstance(lo, float) and math.isnan(lo)):
        return _fmt(mean, digits)
    return f"{_fmt(mean, digits)} [{_fmt(lo, digits)}, {_fmt(hi, digits)}]"


def _table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def _load(cfg, name):
    p = PROJECT_ROOT / cfg["paths"]["results_dir"] / "summary" / f"{name}.csv"
    return pd.read_csv(p) if p.exists() else None


def _meta(cfg, exp, name):
    p = PROJECT_ROOT / cfg["paths"]["results_dir"] / exp / f"{name}.meta.json"
    return json.loads(p.read_text()) if p.exists() else None


def _fig(name):
    return f"![{name}](../outputs/figures/{name}.png)"


def run(cfg: dict, workers: int = 1) -> str:
    out = ["# Results", "",
           "Generated by `python main.py report` from `outputs/results/summary/*.csv`. Every number below comes",
           "from an actual run. Values are **mean [95% CI]** across independent seeds (Student t).",
           "Experiments without data are marked **pending**. Interpretation is in [report.md](report.md).", ""]
    meta = _meta(cfg, "e1_static_scaling", "e1_raw")
    if meta:
        hw = meta["hardware"]
        out += [f"Hardware: {hw['platform']}, {hw['cpu_count']} CPU cores, Python {hw['python']}, "
                f"PyTorch {hw.get('torch')}, MPS available: {hw.get('mps_available')}. "
                f"Code version: `{meta['git_commit']}`.", ""]

    # E1
    s = _load(cfg, "e1_summary")
    out += ["## E1: Static scaling", ""]
    if s is None:
        out += ["**pending**", ""]
    else:
        for d in sorted(s["density"].unique()):
            t = s[s["density"] == d]
            tab = pd.DataFrame({
                "N": t["grid_size"], "planner": t["planner"],
                "time ms": [_ci(r, "wall_time_ms") for _, r in t.iterrows()],
                "expansions": [_ci(r, "expansions") for _, r in t.iterrows()],
                "peak KiB": [_ci(r, "peak_memory_kib") for _, r in t.iterrows()],
                "cost / optimal": [_fmt(v) for v in t["optimality_ratio_mean"]], "n": t["n"]})
            out += [f"### Density {d}", "", _table(tab), ""]
        out += [_fig("e1_runtime_vs_grid"), _fig("e1_expansions_vs_grid"), _fig("e1_memory_vs_grid"), ""]

    # E2
    s = _load(cfg, "e2_summary")
    out += ["## E2: Heuristic quality (A*)", ""]
    if s is None:
        out += ["**pending**", ""]
    else:
        tab = pd.DataFrame({"density": s["density"], "N": s["grid_size"], "heuristic": s["variant"],
                            "expansions": [_ci(r, "expansions") for _, r in s.iterrows()],
                            "time ms": [_ci(r, "wall_time_ms") for _, r in s.iterrows()],
                            "cost / optimal": [_ci(r, "optimality_ratio", 4) for _, r in s.iterrows()],
                            "fraction optimal": [_fmt(v) for v in s["fraction_optimal"]], "n": s["n"]})
        out += [_table(tab), "", _fig("e2_heuristic_quality"), ""]

    # Training
    m = _meta(cfg, "train_dqn", "train_dqn_summary")
    out += ["## DQN / Double DQN training (shared by E3-E5)", ""]
    tr_path = PROJECT_ROOT / cfg["paths"]["results_dir"] / "train_dqn" / "train_dqn_summary.csv"
    if not tr_path.exists():
        out += ["**pending**", ""]
    else:
        tr = pd.read_csv(tr_path)
        cols = ["algorithm", "train_seed", "observation", "device", "train_time_s", "env_steps", "gradient_steps",
                "episodes", "final_success_rate", "converged", "episodes_to_convergence"]
        tab = tr[[c for c in cols if c in tr.columns]].copy()
        tab["train_time_s"] = tab["train_time_s"].map(_fmt)
        out += [_table(tab), "", "`final_success_rate` = greedy success on 50 held-out validation maps at the end of training.",
                "DQN rows trained concurrently with E1/E2/E6 (CPU contention); Double DQN rows trained alone. See methodology §5.",
                "", _fig("train_dqn_validation_curves"), ""]

    # E3
    s = _load(cfg, "e3_summary")
    out += ["## E3: Dynamic obstacles and crossover", ""]
    if s is None:
        out += ["**pending**", ""]
    else:
        tab = pd.DataFrame({"N": s["grid_size"], "change every k": s["change_interval"], "method": s["method"],
                            "computation ms / episode": [_ci(r, "computation_ms") for _, r in s.iterrows()],
                            "success": [_ci(r, "success_f") for _, r in s.iterrows()],
                            "path / static optimum": [_ci(r, "path_cost_ratio") for _, r in s.iterrows()],
                            "replans": [_ci(r, "replans") for _, r in s.iterrows()], "n": s["n"]})
        out += [_table(tab), "", _fig("e3_planning_cost_vs_change_rate"), _fig("e3_methods_vs_change_rate"), ""]
        c = _load(cfg, "e3_crossover")
        if c is not None:
            tab = pd.DataFrame({"change every k": c["change_interval"], "planner": c["planner"], "RL": c["rl_method"],
                                "C_train s": c["train_time_s"].map(_fmt),
                                "c_plan ms/ep": (c["plan_time_per_episode_s"] * 1e3).map(_fmt),
                                "c_infer ms/ep": (c["infer_time_per_episode_s"] * 1e3).map(_fmt),
                                "H* episodes": c["crossover_episodes"].map(_fmt),
                                "planner success": c["planner_success_rate"].map(_fmt),
                                "RL success": c["rl_success_rate"].map(_fmt)})
            out += ["### Crossover (computation only, CPU inference vs CPU planning, GPU training)", "", _table(tab), "",
                    _fig("e3_cumulative_cost_crossover"), _fig("e3_crossover_horizon"), ""]
        inf = _load(cfg, "e3_inference_scaling")
        if inf is not None:
            out += ["### Per-decision cost vs grid size", "",
                    "CNN forward-pass times use untrained networks of the DQN architecture. They measure inference *cost* only.",
                    "No generalist DQN was trained at N > 10, so policy success at those sizes is **pending**.", "",
                    _table(inf.assign(infer_ms=(inf["infer_time_per_step_s"] * 1e3).map(_fmt))[["grid_size", "parameters", "infer_ms"]]),
                    "", _fig("e3_per_decision_cost_vs_grid"), ""]

    # E4
    s = _load(cfg, "e4_summary")
    out += ["## E4: Stochastic transitions", ""]
    if s is None:
        out += ["**pending**", ""]
    else:
        tab = pd.DataFrame({"N": s["grid_size"], "slip": s["slip_prob"], "method": s["method"],
                            "success": [_ci(r, "success_rate") for _, r in s.iterrows()],
                            "return": [_ci(r, "mean_return") for _, r in s.iterrows()],
                            "collisions": [_ci(r, "mean_collisions") for _, r in s.iterrows()],
                            "path deviation": [_ci(r, "mean_path_deviation") for _, r in s.iterrows()], "n": s["n"]})
        out += [_table(tab), "", _fig("e4_success_vs_slip"), ""]

    # E5
    s = _load(cfg, "e5_summary")
    out += ["## E5: Generalization to unseen maps", ""]
    if s is None:
        out += ["**pending**", ""]
    else:
        tab = pd.DataFrame({"method": s["method"], "maps": s["split"],
                            "success": [_ci(r, "success_rate") for _, r in s.iterrows()],
                            "cost / optimal (successes)": [_ci(r, "optimality_ratio") for _, r in s.iterrows()],
                            "n": s["n"]})
        m = _meta(cfg, "e5_generalization", "e5_raw")
        out += [_table(tab), "", f"Train/test map overlap: {m['train_test_map_overlap'] if m else 'n/a'}. "
                "For RL, n = training seeds; for A*, n = test maps.", "", _fig("e5_generalization"), ""]

    # E6
    out += ["## E6: Convergence and learning-rate sensitivity", ""]
    s = _load(cfg, "e6_vi_summary")
    if s is not None:
        t = s[s["density"] == s["density"].min()]
        tab = pd.DataFrame({"N": t["grid_size"], "slip": t["slip_prob"], "sweeps": [_ci(r, "sweeps") for _, r in t.iterrows()],
                            "solve s": [_ci(r, "solve_time_s") for _, r in t.iterrows()], "n": t["n"]})
        out += [f"### Value Iteration (density {t['density'].min()}; convergence = Bellman residual < theta)", "",
                _table(tab), "", _fig("e6_value_iteration"), ""]
    s = _load(cfg, "e6_rl_summary")
    if s is None:
        out += ["RL: **pending**", ""]
    else:
        tab = pd.DataFrame({"algorithm": s["algorithm"], "N": s["grid_size"], "lr": s["learning_rate"],
                            "converged fraction": s["converged_f_mean"].map(_fmt),
                            "episodes to conv. (converged runs)": [_ci(r, "episodes_to_convergence") for _, r in s.iterrows()],
                            "final success": [_ci(r, "final_success_rate") for _, r in s.iterrows()],
                            "train s": [_ci(r, "train_time_s") for _, r in s.iterrows()], "n": s["n"]})
        out += ["### Q-Learning, DQN, Double DQN (one fixed map per seed)", "", _table(tab), "",
                "DQN / Double DQN at N = 30, 50, 70, 100: **pending** (not run, compute budget).", ""]
        for algo in ("q_learning", "dqn", "double_dqn"):
            out += [_fig(f"e6_{algo}_reward_curves"), _fig(f"e6_{algo}_success_curves"),
                    _fig(f"e6_{algo}_lr_bars"), _fig(f"e6_{algo}_heatmap")]
        out += [_fig("e6_convergence_vs_grid"), ""]

    text = "\n".join(out) + "\n"
    (PROJECT_ROOT / "docs" / "RESULTS.md").write_text(text)
    print("Wrote docs/RESULTS.md")
    return text
